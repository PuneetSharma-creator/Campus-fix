REVOKE ALL ON TABLE public.complaints FROM PUBLIC;
REVOKE ALL ON TABLE public.complaints FROM anon;
REVOKE ALL ON TABLE public.complaints FROM authenticated;

-- Step 3b: Grant authenticated users ONLY SELECT and UPDATE on table (strictly governed by RLS)
-- No direct client INSERT or DELETE is granted; submissions proceed exclusively via the Edge Function.
GRANT SELECT, UPDATE ON TABLE public.complaints TO authenticated;

-- Step 3c: Explicitly grant full administrative permissions to postgres and service_role
-- Guarantees the analyze-complaint Edge Function service-role client can insert complaints
GRANT ALL ON TABLE public.complaints TO postgres, service_role;

-- Step 3d: Revoke ALL privileges on the exact identity sequence: public.complaints_id_seq
-- Empirical inspection P6 identified public.complaints_id_seq (owned by postgres) with excessive anon=rwU.
-- In PostgreSQL (version 10+), identity columns (GENERATED BY DEFAULT AS IDENTITY) evaluate
-- sequence defaults internally under table-level INSERT permissions; direct client sequence
-- USAGE or SELECT grants are unnecessary and expose the sequence to unauthorized manipulation.
-- Strip all direct sequence access from PUBLIC, anon, and authenticated.
-- Sequence ownership remains strictly unchanged (owned by postgres).
-- No sequence grants are added to service_role or granted broadly.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relname = 'complaints_id_seq' AND c.relkind = 'S'
  ) THEN
    EXECUTE 'REVOKE ALL ON SEQUENCE public.complaints_id_seq FROM PUBLIC';
    EXECUTE 'REVOKE ALL ON SEQUENCE public.complaints_id_seq FROM anon';
    EXECUTE 'REVOKE ALL ON SEQUENCE public.complaints_id_seq FROM authenticated';
  END IF;
END;
$$;

