-- The legacy live frontend queried public.complaints_public to render a public complaints board.
-- Live inspection confirmed this view is owned by postgres with reloptions {"security_barrier=true"}
-- and anon holds SELECT access.
-- Because it lacks security_invoker=true, it bypasses RLS on public.complaints.
-- Revoking client access from PUBLIC, anon, and authenticated closes this data leak,
-- but WILL IMMEDIATELY BREAK the old public-board frontend (queries fail with error 42501).
-- This migration MUST be coordinated with the deployment of the new frontend and Edge Function.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relname = 'complaints_public' AND c.relkind = 'v'
  ) THEN
    EXECUTE 'REVOKE ALL ON TABLE public.complaints_public FROM PUBLIC';
    EXECUTE 'REVOKE ALL ON TABLE public.complaints_public FROM anon';
    EXECUTE 'REVOKE ALL ON TABLE public.complaints_public FROM authenticated';
    EXECUTE 'GRANT SELECT ON TABLE public.complaints_public TO postgres, service_role';
  END IF;
END;
$$;

-- ------------------------------------------------------------------------------
-- 5. Create Target Row Level Security Policies on public.complaints
-- ------------------------------------------------------------------------------

-- Policy 1: Authenticated SELECT
-- Students read only their own complaints (user_id = auth.uid())
-- Admins read all complaints (including legacy unassigned rows where user_id IS NULL)
-- Anonymous users are completely blocked (policy applies TO authenticated only)
CREATE POLICY "complaints_select"
  ON public.complaints
  FOR SELECT
  TO authenticated
  USING (
    (auth.uid() = user_id)
    OR
    public.is_admin()
  );

-- Policy 2: Admin-Only UPDATE
-- Restricts complaint status changes strictly to verified administrators
-- Evaluated against public.is_admin() in both USING and WITH CHECK
CREATE POLICY "complaints_update_admin"
  ON public.complaints
  FOR UPDATE
  TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

-- Policy Note on INSERT:
-- NO client INSERT policy is created.
-- Combined with REVOKE ALL above, direct browser table insertions are rejected.
-- The Edge Function uses SUPABASE_SERVICE_ROLE_KEY (BYPASSRLS) and inserts seamlessly.

-- Policy Note on DELETE:
-- NO client DELETE policy is created. Deletion is restricted to database administrators.

